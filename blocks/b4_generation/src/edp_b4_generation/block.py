"""Block 4, Generation, as a plug-in (plan §3, Phase 4): design graph in, ``cad_script`` out.

Template first (plan Phase 4 Generation task 1; deck slide 47 template zoo). A design graph no
template matches is flagged ``NO_TEMPLATE`` for a person; the LLM path (code model through the
Model Gateway, deck slide 26 stage 4) is not built yet.
"""

import os
import time
from pathlib import Path

from edp_b4_generation.templates import TEMPLATE_VERSION, NoTemplateError, plan_plate, render_plate
from edp_contracts import Artifact, BlockRequest, BlockResult, Flag
from edp_contracts.artifacts.cad_script import SCHEMA_VERSION, CadScript, ScriptParameter
from edp_contracts.artifacts.design_graph import DesignGraph
from edp_kit import ArtifactStore, pass_through, skip_reason
from edp_kit.passthrough import SKIPPED_SCHEME


class Generation:
    name = "b4_generation"
    version = "0.1.0"
    accepts = {"design_graph"}
    produces = {"cad_script"}

    def __init__(self, store: ArtifactStore | None = None) -> None:
        self._store = store

    @property
    def store(self) -> ArtifactStore:
        if self._store is None:
            from edp_fabric import FabricStore  # entry-point loading: local Fabric (ADR-0008)

            data_dir = os.environ.get("EDP_DATA_DIR")
            if not data_dir:
                raise RuntimeError("Generation needs a store, or EDP_DATA_DIR set to the local data folder")
            self._store = FabricStore(Path(data_dir) / "fabric")
        return self._store

    def run(self, req: BlockRequest) -> BlockResult:
        reason = skip_reason(req)
        if reason:
            return pass_through(self.name, self.produces, req, reason)
        outputs: list[Artifact] = []
        flags: list[Flag] = []
        metrics: dict[str, object] = {}
        for i, art in enumerate(req.inputs):
            started = time.perf_counter()
            graph = DesignGraph.model_validate_json(self.store.read(art.uri))
            try:
                plan = plan_plate(graph)
            except NoTemplateError as exc:
                flags.append(Flag(code="NO_TEMPLATE", message=str(exc), severity="review"))
                metrics[art.uri] = {"template": None}
                # A placeholder keeps the run going once a person approves: blocks 5 to 8 see a
                # skipped input and pass through (ADR-0010) instead of the run stopping for want
                # of a cad_script.
                outputs.append(
                    Artifact(
                        kind="cad_script",
                        uri=f"{SKIPPED_SCHEME}{req.run_id}/{self.name}/cad_script-{i}",
                        schema_version="skipped",
                        sources=art.sources,
                    )
                )
                continue
            script = CadScript(
                language="cadquery",
                code=render_plate(
                    plan, f"Generated by {self.name} {self.version}, template {TEMPLATE_VERSION}."
                ),
                parameters=[
                    ScriptParameter(name=p.name, value=p.value, unit="mm", comment=p.comment, source=p.source)
                    for p in plan.params
                ],
                design_graph_uri=art.uri,
            )
            uri = self.store.write(
                req.run_id, self.name, f"cad_script-{i}.json", script.model_dump_json().encode()
            )
            outputs.append(
                Artifact(kind="cad_script", uri=uri, schema_version=SCHEMA_VERSION, sources=art.sources)
            )
            metrics[art.uri] = {
                "template": TEMPLATE_VERSION,
                "template_only": True,  # plan Phase 4 exit: share of parts generated by templates only
                "parameters": len(script.parameters),
                "seconds": round(time.perf_counter() - started, 4),
            }
        status = "ok" if outputs and not flags else ("needs_review" if outputs or flags else "failed")
        return BlockResult(run_id=req.run_id, status=status, outputs=outputs, flags=flags, metrics=metrics)
